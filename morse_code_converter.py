text = input("What text do you want to convert to Morse?").upper()

output = []
for char in text:
    if char==" ":
        output.append("/")
    elif char in morse_code:
        output.append(morse_code[char])
    else:
        output.append("[?]")
result = " ".join(output)
print(result)



